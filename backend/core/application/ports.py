"""application.ports — Application Ports
=======================================

Ports (interfaces) that define the boundary between the application core and
infrastructure (database, MT5, etc.). The core depends only on these interfaces,
while concrete implementations live in infrastructure packages.
"""

from __future__ import annotations

from typing import Any, Protocol


class MT5Port(Protocol):
    """Subset of MT5 engine needed by the application."""

    def is_connected(self) -> bool: ...
    def get_account_info(self) -> dict[str, Any]: ...
    def get_terminal_info(self) -> dict[str, Any]: ...
    def get_totals(self) -> dict[str, Any]: ...
    def get_symbols(self, group: str | None = None) -> list[str]: ...
    def get_symbol_info(self, symbol: str) -> dict[str, Any]: ...
    def select_symbol(self, symbol: str, enable: bool) -> None: ...
    def get_tick(self, symbol: str) -> dict[str, Any]: ...
    def get_all_ticks(self, names: list[str]) -> list[dict[str, Any]]: ...
    def copy_ticks_range(self, name: str, start: int, end: int, flags: int) -> list[dict[str, Any]]: ...
    def copy_ticks_from(self, name: str, flags: int, count: int) -> list[dict[str, Any]]: ...
    def copy_rates_from(self, name: str, timeframe: int, start: int, count: int) -> list[dict[str, Any]]: ...
    def copy_rates_range(self, name: str, timeframe: int, start: int, end: int) -> list[dict[str, Any]]: ...
    def execute_order(self, request: dict[str, Any]) -> dict[str, Any]: ...
    def check_order(self, request: dict[str, Any]) -> dict[str, Any]: ...
    def buy(self, **kwargs: Any) -> dict[str, Any]: ...
    def sell(self, **kwargs: Any) -> dict[str, Any]: ...
    def close_position(self, **kwargs: Any) -> dict[str, Any]: ...
    def close_all(self, **kwargs: Any) -> list[dict[str, Any]]: ...
    def modify_position(self, **kwargs: Any) -> dict[str, Any]: ...
    def cancel_order(self, **kwargs: Any) -> dict[str, Any]: ...
    def calc_margin(self, name: str, volume: float, otype: int, price: float) -> float: ...
    def calc_profit(self, name: str, volume: float, otype: int, open_price: float, close_price: float) -> float: ...
    def calc_size(self, name: str, volume: float, otype: int, open_price: float, close_price: float) -> float: ...
    def get_history_deals(self, start: int, end: int, symbol: str | None = None) -> list[dict[str, Any]]: ...
    def get_history_orders(self, start: int, end: int, symbol: str | None = None) -> list[dict[str, Any]]: ...
    def history_deals_total(self, start: int, end: int) -> int: ...
    def history_orders_total(self, start: int, end: int) -> int: ...
    def last_error(self) -> dict[str, Any]: ...
    def invalidate_symbol_cache(self) -> None: ...
    def symbol_cache_info(self) -> dict[str, Any]: ...
    def get_positions(self) -> list[dict[str, Any]]: ...
    @property
    def market_book(self) -> Any: ...  # TODO: proper type
    def on_disconnect(self, callback: Any) -> None: ...
    def start_auto_reconnect(self, interval: float = 0) -> None: ...
    def disconnect(self) -> None: ...


class MarketDataPort(Protocol):
    """Port for fetching market data (used by research)."""

    def get_candles(
        self, symbol: str, timeframe: int, start: int, count: int
    ) -> list[dict[str, Any]]: ...
    def get_ticks(
        self, symbol: str, start: int, count: int
    ) -> list[dict[str, Any]]: ...
    def get_symbols(self) -> list[str]: ...
    def get_symbol_info(self, symbol: str) -> dict[str, Any]: ...


class AccountPort(Protocol):
    """Port for account information."""

    def get_account_info(self) -> dict[str, Any]: ...
    def get_balance(self) -> float: ...
    def get_equity(self) -> float: ...


class TradingPort(Protocol):
    """Port for trading operations."""

    def execute_order(self, request: dict[str, Any]) -> dict[str, Any]: ...
    def close_position(self, ticket: int, **kwargs: Any) -> dict[str, Any]: ...
    def modify_position(self, ticket: int, **kwargs: Any) -> dict[str, Any]: ...
    def cancel_order(self, ticket: int) -> dict[str, Any]: ...


class StrategyRepository(Protocol):
    """Port for strategy persistence."""

    def load(self, name: str) -> dict[str, Any] | None: ...
    def save(self, name: str, strategy: dict[str, Any]) -> None: ...
    def delete(self, name: str) -> None: ...
    def list_names(self) -> list[str]: ...


class ReportRepository(Protocol):
    """Port for report persistence."""

    def load(self, name: str) -> dict[str, Any] | None: ...
    def save(self, name: str, report: dict[str, Any]) -> None: ...
    def delete(self, name: str) -> None: ...
    def list_names(self) -> list[str]: ...


class PatternHitRepository(Protocol):
    """Port for pattern hit persistence."""

    def add(self, hit: dict[str, Any]) -> None: ...
    def get_for_strategy(self, strategy_name: str) -> list[dict[str, Any]]: ...
    def clear_for_strategy(self, strategy_name: str) -> None: ...
    def get_all(self) -> list[dict[str, Any]]: ...
    def delete_all(self) -> None: ...


class ConnectionPort(Protocol):
    """Port for MT5 connection management."""

    def connect(self) -> bool: ...
    def is_connected(self) -> bool: ...
    def disconnect(self) -> None: ...
    def on_disconnect(self, callback: Any) -> None: ...
    def start_auto_reconnect(self, interval: float = 0) -> None: ...
